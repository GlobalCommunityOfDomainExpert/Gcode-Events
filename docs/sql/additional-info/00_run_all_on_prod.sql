ALTER TABLE EVENTS ADD CONSTRAINT CK_EVENTS_AUDIO_RECORDING_ENABLED
  CHECK (AUDIO_RECORDING_ENABLED IN (0,1));
ALTER TABLE EVENTS ADD CONSTRAINT CK_EVENTS_AGE_CATEGORY_REQUIREMENT
  CHECK (AGE_CATEGORY_REQUIREMENT IN ('OFF','OPTIONAL','REQUIRED'));
ALTER TABLE EVENTS ADD CONSTRAINT CK_EVENTS_TRACK_SUBMISSION_ENABLED
  CHECK (TRACK_SUBMISSION_ENABLED IN (0,1));
ALTER TABLE EVENTS ADD CONSTRAINT CK_EVENTS_MEMBER_NAMES_ENABLED
  CHECK (MEMBER_NAMES_ENABLED IN (0,1));

-- AUDIO_RECORDING_ENABLED=1 / AGE_CATEGORY_REQUIREMENT='OPTIONAL' preserve
-- today's unconditional-ask behavior for every existing event row.
-- TRACK_SUBMISSION_ENABLED=0 / MEMBER_NAMES_ENABLED=0 default off — brand
-- new, opt-in features with no prior behavior to preserve.

-- Participant-submitted, not organizer-authored — same ownership as the
-- existing audio submission. FK to the participant, not the event.

CREATE TABLE PARTICIPANT_YOUTUBE_TRACKS (
  ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  PARTICIPANT_ID NUMBER NOT NULL,
  TRACK_NAME     VARCHAR2(200) NOT NULL,
  YOUTUBE_URL    VARCHAR2(1000) NOT NULL,
  SORT_ORDER     NUMBER DEFAULT 0,
  CONSTRAINT PK_PARTICIPANT_YOUTUBE_TRACKS PRIMARY KEY (ID),
  CONSTRAINT FK_YOUTUBE_TRACKS_PARTICIPANT FOREIGN KEY (PARTICIPANT_ID)
    REFERENCES GCODE_EVENT_PARTICIPANTS(ID) ON DELETE CASCADE
);

CREATE TABLE PARTICIPANT_TEAM_MEMBERS (
  ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
  PARTICIPANT_ID NUMBER NOT NULL,
  MEMBER_NAME    VARCHAR2(200) NOT NULL,
  SORT_ORDER     NUMBER DEFAULT 0,
  CONSTRAINT PK_PARTICIPANT_TEAM_MEMBERS PRIMARY KEY (ID),
  CONSTRAINT FK_TEAM_MEMBERS_PARTICIPANT FOREIGN KEY (PARTICIPANT_ID)
    REFERENCES GCODE_EVENT_PARTICIPANTS(ID) ON DELETE CASCADE
