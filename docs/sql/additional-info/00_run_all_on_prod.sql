ALTER TABLE EVENTS ADD (
  AUDIO_RECORDING_ENABLED   NUMBER(1,0) DEFAULT 1 NOT NULL,
  AGE_CATEGORY_REQUIREMENT  VARCHAR2(20) DEFAULT 'OPTIONAL' NOT NULL,
  TRACK_SUBMISSION_ENABLED  NUMBER(1,0) DEFAULT 0 NOT NULL,
  MEMBER_NAMES_ENABLED      NUMBER(1,0) DEFAULT 0 NOT NULL
